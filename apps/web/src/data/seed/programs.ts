import type { ItemBlock, Program, ProgramDay, ProgramItem } from "../types";

// Готовые шаблоны. Все программы идут «по очереди»: следующая тренировка — следующий день
// программы, независимо от дня недели. Подходят для нерегулярного графика.
// "a|b|c" в id упражнения — чередование по циклам: 1-й проход программы — a, 2-й — b, 3-й — c, затем снова a.
// Базовые упражнения (жим, подтягивания, присед) не чередуются, чтобы по ним был виден прогресс.

type ItemSpec = [exerciseId: string, sets: number, reps: string, restSec: number, block?: ItemBlock, note?: string];

function parseReps(reps: string): Pick<ProgramItem, "repsMin" | "repsMax" | "durationSec"> {
  if (reps.endsWith("s")) return { durationSec: Number(reps.slice(0, -1)) };
  const [a, b] = reps.split("-").map(Number);
  return { repsMin: a, repsMax: b ?? a };
}

function day(programId: string, index: number, name: string, focus: string, specs: ItemSpec[]): ProgramDay {
  return {
    id: `${programId}.d${index}`,
    name,
    focus,
    items: specs.map(([ids, sets, reps, restSec, block = "main", note], i) => ({
      id: `${programId}.d${index}.i${i}`,
      exerciseId: ids.split("|")[0],
      ...(ids.includes("|") ? { variants: ids.split("|").slice(1) } : {}),
      block,
      sets,
      restSec,
      ...(note ? { note } : {}),
      ...parseReps(reps),
    })),
  };
}

